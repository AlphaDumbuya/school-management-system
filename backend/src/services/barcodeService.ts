import { logger } from '../utils/logger.js';

/**
 * Barcode Service
 * Phase 2.1: Identity Management Module
 * 
 * Handles traditional barcode generation in multiple formats (Code 128, Code 39, EAN-13)
 * for legacy scanning systems. Validates user IDs for format compatibility and generates
 * barcodes with human-readable text.
 * 
 * Note: This service generates barcode data. The actual image generation will be handled
 * by the PDF generation layer using PDFKit which has built-in barcode support or
 * by a separate frontend library for display purposes.
 */

export type BarcodeFormat = 'CODE128' | 'CODE39' | 'EAN13';

export interface BarcodeData {
  format: BarcodeFormat;
  content: string;
  imageDataUrl?: string;  // Optional - will be generated by PDF layer
}

export class BarcodeService {
  /**
   * Generate a barcode in the specified format
   * Requirements: 3.1, 3.2, 3.3
   */
  async generateBarcode(userId: string, format: BarcodeFormat = 'CODE128'): Promise<BarcodeData> {
    try {
      // Validate user ID for the specified format
      if (!this.validateUserIdForFormat(userId, format)) {
        throw new Error(
          `User ID "${userId}" is not compatible with ${format} barcode format`
        );
      }

      logger.info(`Generated ${format} barcode data for user ${userId}`);

      return {
        format,
        content: userId,
      };
    } catch (error) {
      logger.error('Failed to generate barcode', { userId, format, error });
      throw error;
    }
  }

  /**
   * Validate if user ID is compatible with barcode format
   * Requirements: 3.5
   */
  validateUserIdForFormat(userId: string, format: BarcodeFormat): boolean {
    switch (format) {
      case 'CODE128':
        // Code 128 supports full ASCII character set (0-127)
        // Maximum length is typically 80 characters
        return userId.length > 0 && userId.length <= 80;

      case 'CODE39':
        // Code 39 supports: 0-9, A-Z, space, and -.$/%+
        // Maximum length typically around 30-40 characters
        const code39Pattern = /^[0-9A-Z\-\.\$\/\+% ]+$/;
        return (
          userId.length > 0 &&
          userId.length <= 40 &&
          code39Pattern.test(userId)
        );

      case 'EAN13':
        // EAN-13 requires exactly 13 digits
        const ean13Pattern = /^\d{13}$/;
        return ean13Pattern.test(userId);

      default:
        return false;
    }
  }

  /**
   * Get recommended barcode format for a user ID
   */
  getRecommendedFormat(userId: string): BarcodeFormat {
    // Check if EAN-13 compatible
    if (this.validateUserIdForFormat(userId, 'EAN13')) {
      return 'EAN13';
    }

    // Check if Code 39 compatible
    if (this.validateUserIdForFormat(userId, 'CODE39')) {
      return 'CODE39';
    }

    // Default to Code 128 (most flexible)
    return 'CODE128';
  }

  /**
   * Get format capabilities and constraints
   */
  getFormatInfo(format: BarcodeFormat): {
    name: string;
    description: string;
    characterSet: string;
    maxLength: number;
  } {
    switch (format) {
      case 'CODE128':
        return {
          name: 'Code 128',
          description: 'High-density barcode supporting full ASCII character set',
          characterSet: 'Full ASCII (0-127)',
          maxLength: 80,
        };

      case 'CODE39':
        return {
          name: 'Code 39',
          description: 'Alphanumeric barcode widely used in legacy systems',
          characterSet: '0-9, A-Z, -.$/+% and space',
          maxLength: 40,
        };

      case 'EAN13':
        return {
          name: 'EAN-13',
          description: 'International article number barcode',
          characterSet: 'Numeric only',
          maxLength: 13,
        };

      default:
        throw new Error(`Unknown barcode format: ${format}`);
    }
  }
}
